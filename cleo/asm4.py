import struct
code=[]; labels={}; fix=[]
def cur(): return sum(len(c) for c in code)
def op(o,*args):
    b=struct.pack("<H",o)
    for a in args:
        if isinstance(a,tuple):
            t,v=a
            if t=="L": b+=b"\x03"+struct.pack("<H",v)
            elif t=="G": b+=b"\x02"+struct.pack("<H",v)
            elif t=="lab": b+=b"\x01"; fix.append((cur()+len(b),v)); b+=b"\0\0\0\0"
        elif isinstance(a,float): b+=b"\x06"+struct.pack("<f",a)
        elif isinstance(a,int):
            if -128<=a<=127: b+=b"\x04"+struct.pack("<b",a)
            elif -32768<=a<=32767: b+=b"\x05"+struct.pack("<h",a)
            else: b+=b"\x01"+struct.pack("<i",a)
    code.append(b)
def lab(n): labels[n]=cur()
